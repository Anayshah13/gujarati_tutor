export function pickRandomBandQuestion(band: number, excludeIds: Set<string>): QuizQuestion {
  const pool = BAND_QUESTIONS.filter((q) => q.band === band && !excludeIds.has(q.id))
  if (pool.length > 0) {
    return pool[Math.floor(Math.random() * pool.length)]!
  }
  const anyPool = BAND_QUESTIONS.filter((q) => !excludeIds.has(q.id))
  return anyPool[Math.floor(Math.random() * anyPool.length)] ?? BAND_QUESTIONS[0]!
}
